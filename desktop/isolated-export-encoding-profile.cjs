/** D3.3-A: isolated argument builder; integration quality, not production quality. */
const path=require('node:path');
function buildEncodingArgs({format='webm',width,height,fps,hasAudio,audioFile,output}={}){
 if(!['webm','mp4','mov'].includes(format))throw new TypeError('Invalid export format');
 if(!Number.isSafeInteger(width)||!Number.isSafeInteger(height)||width<2||height<2||width*height*4>64*1024*1024)throw new RangeError('Invalid frame dimensions');
 if(!Number.isFinite(fps)||fps<=0||fps>240)throw new RangeError('Invalid fps');
 if(format!=='webm'&&(width%2||height%2))throw new RangeError('MP4/MOV requires even dimensions');
 if(typeof hasAudio!=='boolean')throw new TypeError('Invalid audio availability');
 // Paths are generated by the trusted sink, never supplied by renderer IPC.
 if(typeof output!=='string'||!path.isAbsolute(output)||path.extname(output)!=='.'+format||output.includes('\0'))throw new TypeError('Invalid output path');
 if(hasAudio&&(typeof audioFile!=='string'||!path.isAbsolute(audioFile)||audioFile.includes('\0')||audioFile===output))throw new TypeError('Invalid audio path');
 const args=['-hide_banner','-loglevel','error','-nostdin','-y','-f','rawvideo','-pixel_format','rgba','-video_size',width+'x'+height,'-framerate',String(fps),'-i','pipe:0'];
 if(hasAudio)args.push('-f','f32le','-ar','48000','-ac','1','-i',audioFile);
 args.push('-map','0:v:0',...(hasAudio?['-map','1:a:0']:[]));
 if(format==='webm')args.push('-c:v','libvpx','-pix_fmt','yuv420p','-auto-alt-ref','0','-b:v','1M',...(hasAudio?['-c:a','libopus']:['-an']));
 else args.push('-c:v','h264_videotoolbox','-pix_fmt','yuv420p','-b:v','2000k',...(hasAudio?['-c:a','aac','-b:a','128k']:['-an']),'-movflags','+faststart');
 args.push('-f',format,output);
 return Object.freeze(args);
}
module.exports={buildEncodingArgs};
