import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {registerIsolatedExportIpc,CHANNELS}=require('../desktop/isolated-export-ipc-registration.cjs');
const {createIsolatedExportSessions}=require('../desktop/isolated-export-sessions.cjs');
const owner={mainFrame:{url:'file:///app/index.html'}},window={webContents:owner};
const event={sender:owner,senderFrame:owner.mainFrame},bad={sender:{},senderFrame:owner.mainFrame};
const handlers=new Map(),ipcMain={handle:(name,fn)=>{if(handlers.has(name))throw Error('duplicate');handlers.set(name,fn)},removeHandler:name=>handlers.delete(name)};
const sessions=createIsolatedExportSessions({startExport:async()=>true});
const opts={ipcMain,sessions,window,pageURL:owner.mainFrame.url,windowIsUsable:w=>w===window};
const off=registerIsolatedExportIpc(opts);assert.equal(off.enabled,false);assert.equal(handlers.size,0);
const on=registerIsolatedExportIpc({...opts,enabled:true});assert.equal(on.enabled,true);assert.deepEqual([...handlers.keys()],CHANNELS);
const request={projectId:'p1',width:32,height:32,fps:24,outputName:'video.webm'};
assert.throws(()=>handlers.get(CHANNELS[0])(bad,request),/Unauthorized/);
assert.throws(()=>handlers.get(CHANNELS[0])(event,{...request,destination:'/tmp/x'}),/Unexpected/);
const {id}=handlers.get(CHANNELS[0])(event,request);assert.equal(typeof id,'string');
assert.throws(()=>handlers.get(CHANNELS[1])(bad,id),/Unauthorized/);
await on.dispose();assert.equal(handlers.size,0);assert.equal(sessions.activeCount(),0);
await on.dispose();
const broken={handle:(name)=>{if(name===CHANNELS[1])throw Error('registration failed');handlers.set(name,()=>{})},removeHandler:name=>handlers.delete(name)};
assert.throws(()=>registerIsolatedExportIpc({...opts,ipcMain:broken,enabled:true}),/registration failed/);assert.equal(handlers.size,0);
console.log('RFDR N3.17-D disabled-by-default IPC registration PASS');
