const ipcMain=new EventEmitter(),sent=[];
const contents={mainFrame:{url:'file:///trusted.html'},send:(channel,payload)=>sent.push({channel,payload})};
const window={webContents:contents},trusted={sender:contents,senderFrame:contents.mainFrame};
