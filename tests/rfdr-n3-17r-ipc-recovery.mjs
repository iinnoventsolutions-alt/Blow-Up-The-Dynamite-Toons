import assert from 'node:assert/strict';
import {EventEmitter} from 'node:events';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {createIsolatedBrowserIpc,REPLY_CHANNEL}=require('../desktop/isolated-browser-ipc.cjs');
const ipcMain=new EventEmitter(),requests=[];
const contents={mainFrame:{url:'file:///trusted.html'},send:(channel,payload)=>requests.push(payload)};
const window={webContents:contents},trusted={sender:contents,senderFrame:contents.mainFrame};
const adapter=createIsolatedBrowserIpc({ipcMain,window,pageURL:'file:///trusted.html',windowIsUsable:w=>w===window,enabled:true,frameTimeoutMs:30,audioTimeoutMs:30});
const abort=new AbortController();
const cancelled=adapter.transport.frame(0,2,2,2,abort.signal);
await Promise.resolve();
const old=requests.at(-1);
abort.abort();
await assert.rejects(cancelled,/abort/i);
const retry=adapter.transport.frame(0,2,2,2,new AbortController().signal);
await Promise.resolve();
const next=requests.at(-1);
assert.notEqual(next.token,old.token);
ipcMain.emit(REPLY_CHANNEL,trusted,{token:old.token,kind:'frame',data:{index:0,timestampUs:0,pixels:new Uint8Array(16)}});
ipcMain.emit(REPLY_CHANNEL,{sender:{},senderFrame:contents.mainFrame},{token:next.token,kind:'frame',data:{index:0,timestampUs:0,pixels:new Uint8Array(16)}});
ipcMain.emit(REPLY_CHANNEL,trusted,{token:next.token,kind:'frame',data:{index:0,timestampUs:0,pixels:new Uint8Array(16)}});
assert.equal((await retry).pixels.length,16);
const timeout=adapter.transport.audio(new AbortController().signal);
await assert.rejects(timeout,/timed out/);
const afterTimeout=adapter.transport.audio(new AbortController().signal);
await Promise.resolve();
ipcMain.emit(REPLY_CHANNEL,trusted,{token:requests.at(-1).token,kind:'audio',data:null});
assert.equal(await afterTimeout,null);
adapter.close();
assert.equal(ipcMain.listenerCount(REPLY_CHANNEL),0);
console.log('RFDR N3.17-R cancellation, timeout recovery, and sender isolation PASS');
