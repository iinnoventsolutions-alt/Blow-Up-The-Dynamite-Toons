import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {spawn} from 'node:child_process';
import {makeProject,makePanel} from '../src/model.ts';
const server=process.env.APP_URL?null:spawn(process.execPath,['desktop/preview.cjs'],{stdio:'ignore'});
const url=process.env.APP_URL||'http://127.0.0.1:4317';
for(let i=0;i<100;i++){try{if((await fetch(url)).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const page=await browser.newPage({viewport:{width:1500,height:1000}});
page.setDefaultTimeout(10000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const frame=async()=>Number((await page.getByRole('slider',{name:'Timeline playhead'}).getAttribute('aria-valuenow')));
const time=async controls=>(await controls.innerText()).match(/\d\d:\d\d:\d\d/)?.[0];
try {
 await page.goto(url);
 const p=makeProject('P3 pause stop resume');
 p.scenes[0].panels.push(makePanel('Panel 2'));
 p.scenes[0].panels.forEach(panel=>panel.duration=120);
 await page.locator('input[type=file]').first().setInputFiles({name:'p3.issb',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(p))});
 const drawing=page.getByLabel('Drawing playback controls',{exact:true});
 await drawing.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForTimeout(390);
 await drawing.getByRole('button',{name:'Pause',exact:true}).click();
 const pausedTime=await time(drawing);
 assert(pausedTime&&pausedTime!=='00:00:00','Pause preserves a nonzero position');
 await page.waitForTimeout(200);
 assert.equal(await time(drawing),pausedTime,'Drawing Pause retains frame');
 await drawing.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForTimeout(330);
 await drawing.getByRole('button',{name:'Pause',exact:true}).click();
 assert.notEqual(await time(drawing),pausedTime,'Drawing resume advances from paused frame');
 await drawing.getByTitle('Stop playback').click();
 assert.equal(await time(drawing),'00:00:00','Drawing Stop rewinds');
 assert.equal(await page.getByLabel('Drawing canvas',{exact:true}).count(),1,'Drawing Stop restores editor');
 await page.getByRole('button',{name:'Timeline',exact:true}).click();
 const timeline=page.getByLabel('Timeline playback controls',{exact:true});
 await timeline.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForTimeout(350);
 await timeline.getByRole('button',{name:'Pause',exact:true}).click();
 const paused=await frame();assert(paused>0,'Timeline Pause preserves playhead');
 await page.waitForTimeout(200);assert.equal(await frame(),paused,'Timeline paused frame stays fixed');
 await timeline.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForTimeout(350);
 await timeline.getByRole('button',{name:'Pause',exact:true}).click();
 assert(await frame()>paused,'Timeline resume continues after pause');
 await timeline.getByTitle('Stop playback').click();
 assert.equal(await frame(),0,'Timeline Stop resets playhead');
 await page.getByRole('button',{name:'Pitch',exact:true}).click();
 const pitch=page.locator('.pitch-controls');
 await pitch.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForTimeout(420);
 await pitch.getByRole('button',{name:'Pause',exact:true}).click();
 const frozen=await time(pitch);assert(frozen&&frozen!=='00:00:00','Pitch Pause preserves frame');
 await page.waitForTimeout(190);
 assert.equal(await time(pitch),frozen,'Pitch Pause stays at position');
 await pitch.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForTimeout(290);
 await pitch.getByRole('button',{name:'Pause',exact:true}).click();
 assert.notEqual(await time(pitch),frozen,'Pitch resume advances');
 await pitch.getByTitle('Stop playback').click();
 assert.equal(await time(pitch),'00:00:00','Pitch Stop resets to start');
 await pitch.getByRole('button',{name:'Play',exact:true}).click();
 await page.waitForTimeout(200);
 await pitch.getByTitle('Next panel').click();
 assert.equal(await pitch.getByRole('button',{name:'Play',exact:true}).count(),1,'Pitch navigation pauses playback');
 const afterNavigate=await time(pitch);
 await page.waitForTimeout(160);
 assert.equal(await time(pitch),afterNavigate,'Navigation position stable after pausing');
 assert.deepEqual(errors,[]);
 console.log('PASS V1124-P3: Drawing, Timeline, Pitch pause/resume/stop; pitch navigation pauses; playhead remains stable.');
}finally{await browser.close();server?.kill();}
